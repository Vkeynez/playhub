// Writes src/generated/optionalUi.ts: lazy loaders for game UI packages that are being built by
// other workstreams. A UI is wired in only once its package exports `./ui` and the file exists, so
// the client keeps building before it lands and picks it up on the next build without code edits.
//   node scripts/prepare-registry.mjs
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const games = path.resolve(root, '../../packages/games');
const OPTIONAL = [{ id: 'cricket', dir: 'cricket' }];

const found = [];
for (const game of OPTIONAL) {
  const pkgPath = path.join(games, game.dir, 'package.json');
  if (!existsSync(pkgPath)) continue;
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  const entry = pkg.exports?.['./ui'];
  if (typeof entry === 'string' && existsSync(path.join(games, game.dir, entry))) {
    found.push({ id: game.id, specifier: `${pkg.name}/ui` });
  }
}

const lines = found.map((g) => `  '${g.id}': () => import('${g.specifier}').then(adaptUiModule),`);
const adaptImport = found.length > 0 ? "import { adaptUiModule } from '../registry/adapt';\n" : '';
const ts = `// Generated by scripts/prepare-registry.mjs. Do not edit.
${adaptImport}import type { GameUiModule } from '../room/types';

export const optionalUi: Readonly<Record<string, () => Promise<GameUiModule>>> = {${
  lines.length > 0 ? `\n${lines.join('\n')}\n` : ''
}};
`;
const out = path.join(root, 'src/generated/optionalUi.ts');
mkdirSync(path.dirname(out), { recursive: true });
if (!existsSync(out) || readFileSync(out, 'utf8') !== ts) writeFileSync(out, ts);
process.stdout.write(`optional game UIs: ${found.map((g) => g.id).join(', ') || 'none yet'}\n`);
