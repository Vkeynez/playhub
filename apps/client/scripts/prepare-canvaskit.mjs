// Derives the CanvasKit version from the canvaskit-wasm resolved under the *installed* Skia
// (CLAUDE.md gotcha: never hard-code it), copies the wasm Skia actually loads (bin/full) to
// public/canvaskit/<ver>/canvaskit.wasm (Expo serves public/ in dev and copies it into dist/ on
// export), and writes src/generated/canvaskit.ts. Pattern proven in spikes/render-stress.
//
//   node scripts/prepare-canvaskit.mjs            # wasm + ts
//   node scripts/prepare-canvaskit.mjs --ts-only  # ts only (typecheck)
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import process from 'node:process';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'package.json'));
const skiaPkg = require.resolve('@shopify/react-native-skia/package.json');
const ckPkgPath = createRequire(skiaPkg).resolve('canvaskit-wasm/package.json');
const ckVersion = JSON.parse(readFileSync(ckPkgPath, 'utf8')).version;
const skiaVersion = JSON.parse(readFileSync(skiaPkg, 'utf8')).version;
const wasmPath = path.join(path.dirname(ckPkgPath), 'bin/full/canvaskit.wasm');
const wasm = readFileSync(wasmPath);
const sha384 = 'sha384-' + createHash('sha384').update(wasm).digest('base64');

if (!process.argv.includes('--ts-only')) {
  const outDir = path.join(root, 'public/canvaskit', ckVersion);
  const out = path.join(outDir, 'canvaskit.wasm');
  if (!existsSync(out) || readFileSync(out).length !== wasm.length) {
    mkdirSync(outDir, { recursive: true });
    copyFileSync(wasmPath, out);
  }
}

const ts = `// Generated by scripts/prepare-canvaskit.mjs from the installed Skia. Do not edit.
export const SKIA_VERSION = '${skiaVersion}';
export const CANVASKIT_VERSION = '${ckVersion}';
export const CANVASKIT_WASM_BYTES = ${wasm.length};
export const CANVASKIT_WASM_SHA384 = '${sha384}';
`;
const tsPath = path.join(root, 'src/generated/canvaskit.ts');
mkdirSync(path.dirname(tsPath), { recursive: true });
if (!existsSync(tsPath) || readFileSync(tsPath, 'utf8') !== ts) writeFileSync(tsPath, ts);
process.stdout.write(`canvaskit ${ckVersion} (skia ${skiaVersion}, ${wasm.length} B)\n`);
