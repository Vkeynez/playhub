// Derives the CanvasKit version from the canvaskit-wasm resolved under the *installed* Skia
// (CLAUDE.md gotcha: never hard-code it), copies the wasm Skia actually loads (bin/full) to
// public/canvaskit/<ver>/canvaskit.wasm, and writes src/generated/canvaskitInfo.ts with the
// version, byte size and an SRI sha384.
//   ../../scripts/isolated.sh node scripts/prepare-canvaskit.mjs
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, brotliCompressSync, constants } from 'node:zlib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(path.join(root, 'package.json'));
const skiaPkg = require.resolve('@shopify/react-native-skia/package.json');
const fromSkia = createRequire(skiaPkg);
const ckPkgPath = fromSkia.resolve('canvaskit-wasm/package.json');
const ckVersion = JSON.parse(readFileSync(ckPkgPath, 'utf8')).version;
const skiaVersion = JSON.parse(readFileSync(skiaPkg, 'utf8')).version;
const wasmPath = path.join(path.dirname(ckPkgPath), 'bin/full/canvaskit.wasm');
const wasm = readFileSync(wasmPath);

const sha384 = 'sha384-' + createHash('sha384').update(wasm).digest('base64');
const gz = gzipSync(wasm, { level: 9 }).length;
const br = brotliCompressSync(wasm, {
  params: { [constants.BROTLI_PARAM_QUALITY]: 11, [constants.BROTLI_PARAM_SIZE_HINT]: wasm.length },
}).length;

const outDir = path.join(root, 'public/canvaskit', ckVersion);
mkdirSync(outDir, { recursive: true });
copyFileSync(wasmPath, path.join(outDir, 'canvaskit.wasm'));

mkdirSync(path.join(root, 'src/generated'), { recursive: true });
writeFileSync(
  path.join(root, 'src/generated/canvaskitInfo.ts'),
  `// Generated by scripts/prepare-canvaskit.mjs. Do not edit.
export const SKIA_VERSION = '${skiaVersion}';
export const CANVASKIT_VERSION = '${ckVersion}';
export const CANVASKIT_WASM_BYTES = ${wasm.length};
export const CANVASKIT_WASM_SHA384 = '${sha384}';
`,
);

console.log(
  JSON.stringify(
    {
      skia: skiaVersion,
      canvaskitWasm: ckVersion,
      wasm: path.relative(root, wasmPath),
      rawBytes: wasm.length,
      gzip9Bytes: gz,
      brotli11Bytes: br,
      sha384,
    },
    null,
    2,
  ),
);
